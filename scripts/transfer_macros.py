"""Write LaTeX macros for the cross-city warm-start study from run records and the transfer summaries."""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

PAIRS = {"xian_to_amsterdam": "XianAms", "amsterdam_to_xian": "AmsXian"}
COND = {"scratch": "Scratch", "full": "Full", "encoder_only": "Encoder", "heads_only": "Heads",
        "full_frozen_enc": "FrozenTransferred", "random_frozen_enc": "FrozenRandom"}


def main() -> None:
    lines = ["% Generated by scripts/transfer_macros.py. Do not edit by hand."]
    add = lambda n, v: lines.append(f"\\newcommand{{\\{n}}}{{{v}}}")
    for pair, pt in PAIRS.items():
        summ = json.loads((ROOT / f"results/summary/transfer_{pair}.json").read_text())["budgets"]["reduced"]
        tests = {(t["condition"], t["outcome"]): t for t in summ["tests"]}
        base = np.array([_eum(pair, "scratch", s) for s in range(5)])
        add(f"Tr{pt}ScratchEum", f"{base.mean():.3f}".replace("-", "$-$"))
        for c, ct in COND.items():
            if c == "scratch":
                continue
            vals = np.array([_eum(pair, c, s) for s in range(5)])
            add(f"Tr{pt}{ct}Eum", f"{vals.mean():.3f}".replace("-", "$-$"))
            add(f"Tr{pt}{ct}Diff", f"{(vals - base).mean():+.3f}".replace("-", "$-$"))
            add(f"Tr{pt}{ct}Wins", str(int((vals > base).sum())))
            t = tests[(c, "final_eum")]
            add(f"Tr{pt}{ct}Hl", f"{t['hl_shift']:+.3f}".replace("-", "$-$"))
            add(f"Tr{pt}{ct}HlLo", f"{t['ci95'][0]:+.3f}".replace("-", "$-$"))
            add(f"Tr{pt}{ct}HlHi", f"{t['ci95'][1]:+.3f}".replace("-", "$-$"))
            add(f"Tr{pt}{ct}P", f"{t['p']:.4f}")
            add(f"Tr{pt}{ct}PHolm", f"{t['p_holm']:.3f}")
    out = ROOT / "manuscript/generated/numbers_transfer.tex"
    out.write_text("\n".join(lines) + "\n")
    print("wrote", out, len(lines) - 1, "macros")


def _eum(pair: str, cond: str, seed: int) -> float:
    d = json.loads((ROOT / f"results/transfer/{pair}/{cond}_reduced/seed{seed}.json").read_text())
    return float(d["indicators"]["policy"]["eum"])


if __name__ == "__main__":
    main()
