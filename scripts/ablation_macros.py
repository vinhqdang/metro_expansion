"""Compare the ablations of the RL policy with the full method on matched seeds and write LaTeX macros and a table."""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from src.eval.stats import holm, mwu_a12_boot  # noqa: E402

SEEDS = range(5)
ABL = {"rl_noprior": ("NoPrior", "No scalarised prior"), "rl_single_objective": ("DemandOnly", "Demand-only reward"),
       "rl_flat_encoder": ("NoMessagePassing", "No message passing")}


def rec(method: str, seed: int) -> dict:
    return json.loads((ROOT / f"results/xian_full/{method}/seed{seed}.json").read_text())


def stats(method: str) -> dict:
    eum, hv, lines = [], [], []
    for s in SEEDS:
        d = rec(method, s)
        eum.append(d["indicators"]["policy"]["eum"])
        hv.append(d["indicators"]["archive"]["hv"])
        lines.append(len({tuple(map(tuple, p["cells"])) for p in d["policy_front"] if p["mode"] == "greedy"}))
    return {"eum": np.array(eum), "hv": np.array(hv), "lines": np.array(lines, dtype=float)}


def neg(x: float, d: int = 3) -> str:
    return f"{x:.{d}f}".replace("-", "$-$")


def main() -> None:
    ref = stats("rl_full")
    rows = {m: stats(m) for m in ABL}
    tests = {m: (mwu_a12_boot(r["eum"], ref["eum"]), mwu_a12_boot(r["hv"], ref["hv"])) for m, r in rows.items()}
    ph_e = dict(zip(rows, holm([t[0]["p_mwu"] for t in tests.values()])))
    ph_h = dict(zip(rows, holm([t[1]["p_mwu"] for t in tests.values()])))
    lines = ["% Generated by scripts/ablation_macros.py. Do not edit by hand."]
    add = lambda n, v: lines.append(f"\\newcommand{{\\{n}}}{{{v}}}")
    add("AblFullEum", neg(ref["eum"].mean())); add("AblFullHv", f"{ref['hv'].mean():.3f}"); add("AblFullLines", f"{ref['lines'].mean():.1f}")
    body = [f"Full method (seeds 0--4) & {neg(ref['eum'].mean())} & {ref['hv'].mean():.3f} & {ref['lines'].mean():.1f} & -- & -- \\\\"]
    for m, (tok, label) in ABL.items():
        r = rows[m]; te, th = tests[m]
        add(f"Abl{tok}Eum", neg(r["eum"].mean())); add(f"Abl{tok}Hv", f"{r['hv'].mean():.3f}"); add(f"Abl{tok}Lines", f"{r['lines'].mean():.1f}")
        add(f"Abl{tok}EumDiff", neg(te["mean_diff"])); add(f"Abl{tok}HvDiff", neg(th["mean_diff"]))
        add(f"Abl{tok}EumPHolm", f"{ph_e[m]:.3f}"); add(f"Abl{tok}HvPHolm", f"{ph_h[m]:.3f}")
        body.append(f"{label} & {neg(r['eum'].mean())} & {r['hv'].mean():.3f} & {r['lines'].mean():.1f} & {neg(te['mean_diff'])} ({ph_e[m]:.3f}) & {neg(th['mean_diff'])} ({ph_h[m]:.3f}) \\\\")
    table = ("% Generated by scripts/ablation_macros.py. Do not edit by hand.\n\\begin{table}[t]\n\\centering\n"
             "\\caption{Ablations of the RL policy on Xi'an, five seeds (0--4). EUM: expected utility of the deployable front. Archive HV: hypervolume of the search archive. Lines: distinct lines among the 15 deployable points. Differences are to the full method on the same seeds; Holm-adjusted $p$-values over the three ablations are in parentheses.}\n"
             "\\label{tab:ablation}\n\\small\n\\resizebox{\\textwidth}{!}{%\n\\begin{tabular}{lrrrrr}\n\\toprule\n"
             "Variant & EUM & Archive HV & Lines & $\\Delta$EUM ($p$) & $\\Delta$Archive HV ($p$) \\\\\n\\midrule\n"
             + "\n".join(body) + "\n\\bottomrule\n\\end{tabular}}\n\\end{table}\n")
    gen = ROOT / "manuscript/generated"
    (gen / "numbers_ablation.tex").write_text("\n".join(lines) + "\n")
    (gen / "tab_ablation.tex").write_text(table)
    print("wrote ablation macros and table")


if __name__ == "__main__":
    main()
