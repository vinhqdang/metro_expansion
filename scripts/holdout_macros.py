"""Write LaTeX macros for the line-holdout results from results/summary/xian_line1_holdout.json."""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from src.eval.stats import holm, mwu_a12_boot
TOK = {"rl_full": "RL", "nsga2": "NSGA", "ga_scalar_matched": "GAMatched", "ga_demand": "GADemand", "ga_ggi2": "GAGGI",
       "tabular_eff": "TabDemand", "tabular_ggi2": "TabGGI", "greedy": "Greedy", "random": "Random"}
SEL = {"vertex": "Vertex", "centroid": "Balanced", "archive_best_demand": "ArchiveDemand"}


def fmt(x: float, d: int = 2) -> str:
    return f"{x:.{d}f}"


def main() -> None:
    h = json.loads((ROOT / "results/summary/xian_line1_holdout.json").read_text())
    lines = [f"% Generated by scripts/holdout_macros.py. Do not edit by hand."]
    add = lambda name, val: lines.append(f"\\newcommand{{\\{name}}}{{{val}}}")
    add("HoldoutRealDtot", fmt(h["reference"]["d_tot"], 4))
    add("HoldoutNullN", str(h["null"]["n_lines"]))
    add("HoldoutNullDeadEnd", fmt(100 * h["null"]["n_dead_end"] / h["null"]["n_lines"], 0))
    f1 = {}
    for m, v in h["methods"].items():
        for sel, st in v["selections"].items():
            vals = [s["f1_r1"] for s in st["per_seed"].values()]
            f1[(m, sel)] = vals
            tk = "Holdout" + TOK[m] + SEL[sel]
            add(tk + "FOne", fmt(float(np.mean(vals))))
            add(tk + "FOneSd", fmt(float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0))
            add(tk + "Ratio", fmt(float(np.mean([s["demand_ratio"] for s in st["per_seed"].values()]))))
            add(tk + "Msd", fmt(float(np.mean([s["mean_sym_dist"] for s in st["per_seed"].values()]))))
            pct = st.get("null_percentile", {})
            if isinstance(pct, dict) and pct.get("f1_r1") is not None:
                add(tk + "Pct", fmt(pct["f1_r1"], 1))
    for sel in ("vertex", "centroid"):
        names, ps = [], []
        for m in ("rl_full", "nsga2", "ga_scalar_matched"):
            r = mwu_a12_boot(np.array(f1[(m, sel)]), np.array(f1[("random", sel)]))
            names.append(m); ps.append(r["p_mwu"])
            add("HoldoutVsRandom" + TOK[m] + SEL[sel] + "A", fmt(r["a12"]))
        for m, p in zip(names, holm(ps)):
            add("HoldoutVsRandom" + TOK[m] + SEL[sel] + "PHolm", f"{p:.3f}" if p >= 0.001 else "<0.001")
    out = ROOT / "manuscript/generated/numbers_holdout.tex"
    out.write_text("\n".join(lines) + "\n")
    print("wrote", out, len(lines) - 1, "macros")


if __name__ == "__main__":
    main()
